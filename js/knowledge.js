(function () {
  const gl = document.getElementById("gl");
  const q = document.getElementById("q");
  const empty = document.getElementById("gl-empty");
  const filter = document.getElementById("g-filter");
  let cat = "";

  const esc = (s) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const hi = (s, k) => {
    const t = esc(s);
    if (!k) return t;
    const ek = esc(k).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    return t.replace(new RegExp(ek, "gi"), (m) => `<mark>${m}</mark>`);
  };

  function render() {
    const k = q.value.trim();
    const kl = k.toLowerCase();
    const list = TERMS.filter(([n, en, c, d]) =>
      (!cat || c === cat) && (!kl || (n + en + d).toLowerCase().includes(kl))
    );
    gl.innerHTML = list
      .map(([n, en, c, d]) => `
        <div class="card term">
          <h4>${hi(n, k)}<span class="py">${hi(en, k)}</span></h4>
          <span class="tag${c === "和田玉" ? " gold" : ""}">${c}</span>
          <p>${hi(d, k)}</p>
        </div>`)
      .join("");
    empty.hidden = list.length > 0;
  }

  q.addEventListener("input", render);
  filter.addEventListener("click", (e) => {
    const b = e.target.closest(".chip");
    if (!b) return;
    cat = b.dataset.k;
    filter.querySelectorAll(".chip").forEach((x) => x.classList.toggle("on", x === b));
    render();
  });
  render();
})();
